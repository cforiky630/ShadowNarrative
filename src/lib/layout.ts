/**
 * 页面壳 —— 滚动类页面共用的边距与栏宽（`02 §16`）。
 *
 * 用户 2026-10-11：「统一一下每个画面的视觉大小，提升观感，现在有的界面
 * 大小差异感觉有点突兀」。原先四个页面是四套数字：
 *
 * ```text
 *   时间线       px-6  pt-32 pb-48   max-w-[1100px]
 *   影册（架子）  px-12 pt-32 pb-32   max-w-[880px]
 *   一册         px-12 pt-32 pb-32   max-w-[880px]
 *   整理照片面板  px-6  pt-24 pb-32   max-w-[980px]
 * ```
 *
 * 左右两档、上下三档、栏宽四个数 —— 切一次页面跳一次。
 * 现在取**已有的众数**，而不是另定一套：
 *
 * - **880 / px-12 / pt-32 / pb-32**：影册那两页一个字没动
 * - **时间线**：可见内容也**一像素没动** —— 它的行是绕着**轴**排的，
 *   而轴在栏的中心。栏从 1100 收到 880，两侧各收掉 110px 的空白，
 *   轴与贴着轴的内容（那行日期、主题名）原地不动（实测过：x 一致）
 * - **整理面板**：980 → 880、`px-6` → `px-12`，于是它盖住的还是底下
 *   那一册的同一栏，面板开合的瞬间内容不会横着滑一下
 *
 * ⚠️ **首屏与照片页不在这一条里。** 那两个是满屏的舞台（照片是主体），
 * 不套栏宽。首屏手风琴那个 760 是跟着**媒体框的宽高比**定的 ——
 * 媒体宽 = 栏宽 × 0.634，而它高由视口定，栏一宽照片就被裁得更狠；
 * 那一句「不铺满整屏，两边留白」在 `AlbumSpace` 里。
 *
 * ⚠️ 左右统一到 `px-12`，是因为顶栏就是 `px-12` —— 正文与
 * `Shadow Narrative` 对齐。
 */

/** 页面的内边距。整理照片那张面板只要这一半（它自己是 `fixed` 的整屏层） */
export const PAGE_PAD = "px-12 pt-32 pb-32";

/** 页面外壳：整屏高 + `PAGE_PAD`。给 `<main>` 用 */
export const PAGE_SHELL = `min-h-dvh ${PAGE_PAD}`;

/** 页面里那一栏。与 `PAGE_SHELL` 配套 */
export const PAGE_INNER = "mx-auto w-full max-w-[880px]";
